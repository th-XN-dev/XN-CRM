// Generates src/services/api/schema.gen.ts from openapi.json (exported by the
// backend: `npm run openapi:export` in the repository root). Only the DTO
// schemas are emitted — endpoints are wrapped by hand in each feature's api.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const document = JSON.parse(readFileSync(`${root}openapi.json`, 'utf8'));
const schemas = document.components.schemas;

const refName = (ref) => ref.split('/').pop();
const literal = (value) => (typeof value === 'string' ? `'${value.replace(/'/g, "\\'")}'` : String(value));

function type(schema, indent) {
  if (!schema) return 'unknown';
  let out;
  if (schema.$ref) out = refName(schema.$ref);
  else if (schema.allOf) out = schema.allOf.map((part) => type(part, indent)).join(' & ');
  else if (schema.oneOf || schema.anyOf) out = (schema.oneOf ?? schema.anyOf).map((part) => type(part, indent)).join(' | ');
  else if (schema.enum) out = schema.enum.map(literal).join(' | ');
  else if (schema.type === 'array') {
    const item = type(schema.items, indent);
    out = /[|&]/.test(item) ? `Array<${item}>` : `${item}[]`;
  } else if (schema.type === 'object' || schema.properties) {
    out = schema.properties ? objectType(schema, indent) : 'Record<string, unknown>';
  } else if (schema.type === 'integer' || schema.type === 'number') out = 'number';
  else if (schema.type === 'string' || schema.type === 'boolean') out = schema.type;
  else out = 'unknown';
  return schema.nullable && out !== 'unknown' ? `${out} | null` : out;
}

function objectType(schema, indent) {
  const pad = '  '.repeat(indent + 1);
  const required = new Set(schema.required ?? []);
  const lines = Object.entries(schema.properties).map(([key, value]) => {
    const doc = value.description ? `${pad}/** ${value.description.replace(/\*\//g, '*\\/').replace(/\n/g, ' ')} */\n` : '';
    return `${doc}${pad}${key}${required.has(key) ? '' : '?'}: ${type(value, indent + 1)};`;
  });
  return `{\n${lines.join('\n')}\n${'  '.repeat(indent)}}`;
}

const body = Object.entries(schemas)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, schema]) => `export type ${name} = ${type(schema, 0)};`)
  .join('\n\n');

writeFileSync(
  `${root}src/services/api/schema.gen.ts`,
  `/* Generated by scripts/generate-api-types.mjs from openapi.json — do not edit. */\n/* eslint-disable */\n\n${body}\n`,
);
process.stdout.write(`API types: ${Object.keys(schemas).length} schemas\n`);
